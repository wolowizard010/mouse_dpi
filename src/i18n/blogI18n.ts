export function getBlogUi(locale: string | undefined): BlogUiStrings {
  const lang = (locale && locale in blogUiTranslations ? locale : 'en') as SupportedLocale;
  return blogUiTranslations[lang] || blogUiTranslations.en;
}

export function getPostTranslation(
  slug: string,
  locale: string | undefined
): TranslatedPostData | null {
  if (!locale || locale === 'en') return null;
  const lang = locale as SupportedLocale;
  const postDict = blogPostTranslations[slug];
  if (postDict && postDict[lang]) {
    return postDict[lang]!;
  }
  return null;
}
